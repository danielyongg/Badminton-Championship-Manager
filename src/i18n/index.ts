export type TextKey = keyof typeof id;

export type Lang = 'id' | 'en';
export const LANGS: Lang[] = ['id', 'en'];
const dicts: Record<Lang, Record<TextKey, string>> = { id, en };

// Pilihan bahasa disimpan di browser (per perangkat); tanpa localStorage (mis. tes) → Indonesia.
let lang: Lang = (() => { try { return localStorage.getItem('bcm-lang') === 'en' ? 'en' : 'id'; } catch { return 'id'; } })();
export const getLang = () => lang;
export function setLang(l: Lang) {
  lang = l;
  try { localStorage.setItem('bcm-lang', l); } catch { /* mode privat: hanya untuk sesi ini */ }
}
/** Locale untuk format angka (1.450.000 vs 1,450,000). */
export const numLocale = () => (lang === 'en' ? 'en-US' : 'id-ID');

export const t = (key: TextKey, vars?: Record<string, string | number>) =>
  vars ? dicts[lang][key].replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : dicts[lang][key];

/** Nama data bawaan (negara/kota/event) dalam bahasa terpilih; nama buatan user dikembalikan apa adanya. */
export const dataName = <T extends string | undefined>(name: T): T => (lang === 'en' && name && DATA_EN[name] ? DATA_EN[name] : name) as T;
